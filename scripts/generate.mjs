// Generates `src/generated/openapi.ts` from the Planeward OpenAPI spec.
//
// Source, first match wins:
// 1. `PLANEWARD_OPENAPI` (a file path or an http(s) URL)
// 2. `../../workbench/apps/docs/openapi/v1.yaml` (local Planeward checkout)
// 3. https://docs.planeward.com/openapi.json
//
// `--check` compares against the committed file instead of writing it and
// exits 1 when they differ, so CI never replaces the types later steps use.
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import * as prettier from "prettier";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const LOCAL_SPEC = resolve(root, "../../workbench/apps/docs/openapi/v1.yaml");
const HOSTED_SPEC = "https://docs.planeward.com/openapi.json";
const OUTPUT = resolve(root, "src/generated/openapi.ts");

function resolveSource() {
  const fromEnv = process.env.PLANEWARD_OPENAPI?.trim();
  if (fromEnv) {
    return /^https?:\/\//.test(fromEnv)
      ? new URL(fromEnv)
      : pathToFileURL(resolve(root, fromEnv));
  }
  if (existsSync(LOCAL_SPEC)) return pathToFileURL(LOCAL_SPEC);
  return new URL(HOSTED_SPEC);
}

const source = resolveSource();
console.log(`Generating OpenAPI types from ${source.href}`);

const ast = await openapiTS(source, {
  // Fields with a `default` stay optional in request bodies.
  defaultNonNullable: false,
  // Free-form `type: object` (form `fields`, `settings`) reads as
  // `Record<string, unknown>`, not `Record<string, never>`.
  emptyObjectsUnknown: true,
});
const header =
  "// Generated by `pnpm generate` from the Planeward OpenAPI spec. Do not edit.\n\n";
const code = header + astToString(ast);

const prettierConfig = (await prettier.resolveConfig(OUTPUT)) ?? {};
const formatted = await prettier.format(code, {
  ...prettierConfig,
  filepath: OUTPUT,
});

if (process.argv.includes("--check")) {
  const current = existsSync(OUTPUT) ? await readFile(OUTPUT, "utf8") : "";
  if (current !== formatted) {
    console.error(
      `${OUTPUT} is out of date with ${source.href}. Run \`pnpm generate\`.`
    );
    process.exit(1);
  }
  console.log(`${OUTPUT} is up to date.`);
} else {
  await mkdir(dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, formatted);
  console.log(`Wrote ${OUTPUT}`);
}
